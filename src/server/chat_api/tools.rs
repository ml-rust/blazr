//! OpenAI-compatible tool/function calling types and extraction logic.

use serde::{Deserialize, Serialize};

use crate::model::chat_template::ChatMessage;
use crate::server::multimodal::{ContentPart, MessageContent};

use super::chat_vision::{marked_text, MediaPart};

/// Tool definition in the request
#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct Tool {
    pub r#type: String,
    pub function: ToolFunction,
}

/// Function definition within a tool
#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct ToolFunction {
    pub name: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub parameters: Option<serde_json::Value>,
}

/// A tool call generated by the model
#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct ToolCall {
    pub id: String,
    pub r#type: String,
    pub function: ToolCallFunction,
}

/// Function call details within a tool call
#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct ToolCallFunction {
    pub name: String,
    pub arguments: String,
}

/// Extended chat message for API request/response (supports tool_calls, tool_call_id, multimodal content)
#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct ChatRequestMessage {
    pub role: String,
    /// Content can be a simple string or an array of content parts (text + images + audio).
    /// Supports OpenAI multimodal format:
    /// - `"content": "Hello"` (string)
    /// - `"content": [{"type": "text", "text": "..."}, {"type": "image_url", "image_url": {...}}]` (array)
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub content: Option<MessageContent>,
    /// Tool calls made by the assistant
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_calls: Option<Vec<ToolCall>>,
    /// ID of the tool call this message responds to (role=tool)
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_call_id: Option<String>,
    /// Function name (for role=tool messages)
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
    /// Reasoning the assistant produced before `content`, handed back by a
    /// client on a later turn. A Jinja template decides how to render it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning_content: Option<String>,
}

/// Response message that can contain tool_calls
#[derive(Debug, Clone, Serialize)]
pub struct ChatResponseMessage {
    pub role: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub content: Option<String>,
    /// Reasoning the model produced before `content`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub reasoning_content: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_calls: Option<Vec<ToolCall>>,
}

/// Build a system prompt that describes available tools to the model.
pub fn build_tools_system_prompt(tools: &[Tool]) -> Option<String> {
    if tools.is_empty() {
        return None;
    }
    let mut prompt = String::from("You have access to the following tools:\n\n");
    for tool in tools {
        prompt.push_str(&format!("- {}", tool.function.name));
        if let Some(ref desc) = tool.function.description {
            prompt.push_str(&format!(": {}", desc));
        }
        prompt.push('\n');
        if let Some(ref params) = tool.function.parameters {
            if let Ok(json) = serde_json::to_string_pretty(params) {
                prompt.push_str(&format!("  Parameters: {}\n", json));
            }
        }
    }
    prompt.push_str(
        "\nTo call a tool, respond with: \
         <tool_call>{\"name\": \"function_name\", \"arguments\": {...}}</tool_call>",
    );
    Some(prompt)
}

/// Extract text from a MessageContent (for chat template formatting).
fn content_text(content: &Option<MessageContent>) -> String {
    match content {
        Some(mc) => mc.text(),
        None => String::new(),
    }
}

/// Convert a request message into the shape a chat template renders.
///
/// `structured` is [`ChatTemplate::renders_tools_natively`](crate::model::chat_template::ChatTemplate::renders_tools_natively):
/// a Jinja template takes tool calls and tool results as fields, a built-in
/// format takes them flattened into the content text.
///
/// `image_marker` is what a loaded vision tower expands: with `Some`, every
/// image part becomes that text at its own position among the parts. With
/// `None` an image is a `[image]` note in front of the text. The decoded
/// media travels beside the prompt on both paths.
pub fn request_msg_to_chat_msg(
    msg: &ChatRequestMessage,
    structured: bool,
    image_marker: Option<&str>,
) -> ChatMessage {
    if structured {
        return ChatMessage {
            role: msg.role.clone(),
            content: media_marked_text(msg, image_marker),
            name: msg.name.clone(),
            tool_calls: msg.tool_calls.as_ref().map(|calls| {
                calls
                    .iter()
                    .filter_map(|c| serde_json::to_value(c).ok())
                    .collect()
            }),
            reasoning_content: msg.reasoning_content.clone(),
        };
    }
    let content = match msg.role.as_str() {
        "tool" => {
            // Format tool result: include the function name and result
            let name = msg.name.as_deref().unwrap_or("unknown");
            let text = content_text(&msg.content);
            format!("[Tool Result: {}]\n{}", name, text)
        }
        "assistant" if msg.tool_calls.is_some() => {
            // Format assistant tool calls as text for template
            let mut parts = Vec::new();
            let text = content_text(&msg.content);
            if !text.is_empty() {
                parts.push(text);
            }
            if let Some(ref calls) = msg.tool_calls {
                for call in calls {
                    parts.push(format!(
                        "<tool_call>{{\"name\": \"{}\", \"arguments\": {}}}</tool_call>",
                        call.function.name, call.function.arguments
                    ));
                }
            }
            parts.join("\n")
        }
        _ => media_marked_text(msg, image_marker),
    };

    ChatMessage::new(msg.role.clone(), content)
}

/// The message text with its images marked, through the helper every chat
/// route shares.
fn media_marked_text(msg: &ChatRequestMessage, image_marker: Option<&str>) -> String {
    let Some(mc) = msg.content.as_ref() else {
        return String::new();
    };
    marked_text(&media_parts(mc), image_marker)
}

/// The content as the marker helper reads it: text as is, an image part as an
/// image, audio dropped.
fn media_parts(content: &MessageContent) -> Vec<MediaPart<'_>> {
    match content {
        MessageContent::Text(s) => vec![MediaPart::Text(s.as_str())],
        MessageContent::Parts(parts) => parts
            .iter()
            .map(|p| match p {
                ContentPart::Text { text } => MediaPart::Text(text.as_str()),
                ContentPart::ImageUrl { .. } => MediaPart::Image,
                ContentPart::InputAudio { .. } => MediaPart::Dropped,
            })
            .collect(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn message(role: &str, content: &str) -> ChatRequestMessage {
        ChatRequestMessage {
            role: role.to_string(),
            content: Some(MessageContent::Text(content.to_string())),
            tool_calls: None,
            tool_call_id: None,
            name: None,
            reasoning_content: None,
        }
    }

    #[test]
    fn test_request_msg_to_chat_msg_tool_role() {
        let mut msg = message("tool", "{\"temp\": 20}");
        msg.tool_call_id = Some("call_abc".to_string());
        msg.name = Some("get_weather".to_string());
        let chat_msg = request_msg_to_chat_msg(&msg, false, None);
        assert_eq!(chat_msg.role, "tool");
        assert!(chat_msg.content.contains("[Tool Result: get_weather]"));
        assert!(chat_msg.content.contains("{\"temp\": 20}"));
        assert!(chat_msg.name.is_none());

        let structured = request_msg_to_chat_msg(&msg, true, None);
        assert_eq!(structured.content, "{\"temp\": 20}");
        assert_eq!(structured.name.as_deref(), Some("get_weather"));
    }

    #[test]
    fn test_request_msg_to_chat_msg_assistant_tool_calls() {
        let mut msg = message("assistant", "");
        msg.tool_calls = Some(vec![ToolCall {
            id: "call_1".to_string(),
            r#type: "function".to_string(),
            function: ToolCallFunction {
                name: "get_weather".to_string(),
                arguments: "{\"city\": \"Paris\"}".to_string(),
            },
        }]);
        let flat = request_msg_to_chat_msg(&msg, false, None);
        assert!(flat
            .content
            .starts_with("<tool_call>{\"name\": \"get_weather\""));
        assert!(flat.tool_calls.is_none());

        let structured = request_msg_to_chat_msg(&msg, true, None);
        assert_eq!(structured.content, "");
        let calls = structured.tool_calls.expect("kept as fields");
        assert_eq!(calls[0]["function"]["name"], "get_weather");
        assert_eq!(calls[0]["id"], "call_1");
    }

    #[test]
    fn test_request_msg_to_chat_msg_user() {
        let msg = message("user", "Hello");
        let chat_msg = request_msg_to_chat_msg(&msg, false, None);
        assert_eq!(chat_msg.role, "user");
        assert_eq!(chat_msg.content, "Hello");
    }

    #[test]
    fn test_request_msg_to_chat_msg_multimodal() {
        let msg = ChatRequestMessage {
            role: "user".to_string(),
            content: Some(MessageContent::Parts(vec![
                crate::server::multimodal::ContentPart::Text {
                    text: "What is this?".to_string(),
                },
                crate::server::multimodal::ContentPart::ImageUrl {
                    image_url: crate::server::multimodal::ImageUrl {
                        url: "https://example.com/img.png".to_string(),
                        detail: "auto".to_string(),
                    },
                },
            ])),
            tool_calls: None,
            tool_call_id: None,
            name: None,
            reasoning_content: None,
        };
        for structured in [false, true] {
            let chat_msg = request_msg_to_chat_msg(&msg, structured, None);
            assert_eq!(chat_msg.role, "user");
            assert!(chat_msg.content.contains("[image]"));
            assert!(chat_msg.content.contains("What is this?"));
        }
    }

    /// With a marker, each image sits at its own place among the parts:
    /// two images give two marker groups in message order.
    #[test]
    fn test_request_msg_to_chat_msg_two_images_marked_in_order() {
        use crate::server::multimodal::{ContentPart, ImageUrl};
        let image = |url: &str| ContentPart::ImageUrl {
            image_url: ImageUrl {
                url: url.to_string(),
                detail: "auto".to_string(),
            },
        };
        let msg = ChatRequestMessage {
            role: "user".to_string(),
            content: Some(MessageContent::Parts(vec![
                ContentPart::Text {
                    text: "First:".to_string(),
                },
                image("a.png"),
                ContentPart::Text {
                    text: "Second:".to_string(),
                },
                image("b.png"),
                ContentPart::Text {
                    text: "Compare them.".to_string(),
                },
            ])),
            tool_calls: None,
            tool_call_id: None,
            name: None,
            reasoning_content: None,
        };
        let marker = crate::engine::vision_tower::IMAGE_MARKER_TEXT;
        for structured in [false, true] {
            let chat_msg = request_msg_to_chat_msg(&msg, structured, Some(marker));
            assert_eq!(
                chat_msg.content,
                format!("First:\n{marker}\nSecond:\n{marker}\nCompare them.")
            );
            assert_eq!(chat_msg.content.matches(marker).count(), 2);
            assert!(!chat_msg.content.contains("[image]"));
        }
    }
}
